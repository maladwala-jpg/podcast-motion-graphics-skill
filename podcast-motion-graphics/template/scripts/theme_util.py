"""Colour helpers + theme derivation shared by build_data.py and analyze_video.py.

theme.json only *needs* six colours (primary, secondary, tertiary, quaternary, dark, light). Everything else
(backgrounds, card colours, slat shades, road colour ...) is derived here so a new palette is a 6-line file.
"""
import colorsys, json, os

def hex2rgb(h):
    h = h.lstrip('#')
    if len(h) == 3: h = ''.join(c * 2 for c in h)
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))

def rgb2hex(rgb):
    return '#%02X%02X%02X' % tuple(max(0, min(255, int(round(v)))) for v in rgb)

def mix(a, b, t):
    """t=0 -> a, t=1 -> b"""
    A, B = hex2rgb(a), hex2rgb(b)
    return rgb2hex([A[i] + (B[i] - A[i]) * t for i in range(3)])

def shade(h, k):
    return rgb2hex([c * k for c in hex2rgb(h)])

def hsv(h):
    r, g, b = [c / 255 for c in hex2rgb(h)]
    return colorsys.rgb_to_hsv(r, g, b)

def from_hsv(hh, s, v):
    return rgb2hex([c * 255 for c in colorsys.hsv_to_rgb(hh % 1.0, max(0, min(1, s)), max(0, min(1, v)))])

def luminance(h):
    r, g, b = hex2rgb(h)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b

CORE = ['primary', 'secondary', 'tertiary', 'quaternary', 'dark', 'light']

def complete(theme):
    """Fill every derived token that theme.json did not set explicitly. Returns a new dict."""
    t = dict(theme)
    for k in CORE:
        if k not in t:
            raise SystemExit(f'theme.json is missing required colour "{k}" (need: {", ".join(CORE)})')
    P, S, T, Q, D, L = (t[k] for k in CORE)
    t.setdefault('danger', '#D9503A')
    t.setdefault('primary_d', mix(P, '#000000', 0.15))
    t.setdefault('tertiary_d', mix(T, '#000000', 0.30))
    t.setdefault('accent_light', mix(P, '#000000', 0.06))      # accent word colour on light scenes
    t.setdefault('highlight', mix(S, '#FFFFFF', 0.12))        # accent word colour on dark scenes
    t.setdefault('ink', mix(D, '#000000', 0.10))
    t.setdefault('paper', mix(L, '#FFFFFF', 0.65))            # card colour on light scenes
    t.setdefault('card_dark', mix(D, L, 0.12))                # card colour on dark scenes
    t.setdefault('bg_light', [mix(L, '#FFFFFF', 0.45), mix(L, P, 0.12)])
    t.setdefault('bg_dark', [mix(D, P, 0.10), mix(D, '#000000', 0.35)])
    t.setdefault('road', mix(P, L, 0.78))
    if not t.get('slats'):
        h, s, v = hsv(P)
        t['slats'] = [from_hsv(h + ((i * 7) % 5 - 2) * 0.006, s * (0.93 + ((i * 3) % 5) * 0.03), v * (0.84 + ((i * 5) % 7) * 0.035)) for i in range(12)]
    return t

def to_css(t):
    names = {
        'primary': 'primary', 'primary_d': 'primary-d', 'secondary': 'secondary', 'tertiary': 'tertiary', 'tertiary_d': 'tertiary-d',
        'quaternary': 'quaternary', 'dark': 'dark', 'light': 'light', 'danger': 'danger', 'highlight': 'highlight',
        'accent_light': 'accent-light', 'ink': 'ink', 'paper': 'paper', 'card_dark': 'card-dark',
    }
    lines = [f'  --{css}:{t[k]};' for k, css in names.items()]
    lines += [f'  --bg-light-1:{t["bg_light"][0]};', f'  --bg-light-2:{t["bg_light"][1]};', f'  --bg-dark-1:{t["bg_dark"][0]};', f'  --bg-dark-2:{t["bg_dark"][1]};']
    return '/* generated by scripts/build_data.py from theme.json — do not edit */\n:root{\n' + '\n'.join(lines) + '\n}\n'

def load(path='theme.json'):
    with open(path) as f:
        return complete(json.load(f))
